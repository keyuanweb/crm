/**
 * 表单弹窗的四档宽度。**单独成文件**的理由与 `formGridStyle.ts` 同：
 * `react-refresh/only-export-components`（`eslint.config.js:21`）要求组件文件只导出组件，
 * 而本仓库当前的 lint 是零警告的——为一个常量表破例，后续就会有人以为加 disable 是常规做法。
 *
 * ## 为什么是这四档而不是"允许任意宽度"
 *
 * 实测现状：70 个 Modal 用了 **11 种宽度取值**，另有 **32 个根本没设宽度**（吃 antd 默认 520）。
 * 11 种取值里没有一种是设计意图，全是各页各写一遍。四档覆盖了它们的实际分布，
 * 而 `md = 640` 是现状里出现最多、事实上已成默认的那一档。
 *
 * ## 档位与列数的关系：**没有关系**
 *
 * 起草时这里写过一条"哪档宽度配几列"的规则，那是错的——它把一个本该自动的东西
 * 变成了要靠人记住的约定。列数由 `FormGrid` 的 `auto-fit` 按**容器实际宽度**推导，
 * 所以这张表只管宽度，不管列数。参考值（`labelWidth = 96`、输入框下限 160 → 栅格下限 256）：
 *
 * | 档位 | 弹窗宽 | 可用宽 | 实际列数 |
 * |---|---|---|---|
 * | `sm` | 480 | 432 | 1 |
 * | `md` | 640 | 592 | 2 |
 * | `lg` | 800 | 752 | 2 |
 * | `xl` | 960 | 912 | 3 |
 *
 * 这张表是**推导结果，不是配置**——改 `LABEL_WIDTH` 或输入框下限时它会跟着变，
 * 所以**不要把它当成需要同步维护的第二份真源**。
 */

export type FormModalSize = 'sm' | 'md' | 'lg' | 'xl'

export const FORM_MODAL_WIDTHS: Record<FormModalSize, number> = {
  sm: 480,
  md: 640,
  lg: 800,
  xl: 960,
}
