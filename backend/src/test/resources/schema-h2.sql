CREATE TABLE contact (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT       NOT NULL,
  name        VARCHAR(50)  NOT NULL,
  title       VARCHAR(50),
  phone       VARCHAR(30),
  email       VARCHAR(100),
  role        VARCHAR(30)  NOT NULL DEFAULT 'OTHER',
  remark      VARCHAR(500),
  deleted     INT          DEFAULT 0,
  version     INT          DEFAULT 0,
  created_by  BIGINT,
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_contact_deleted_customer ON contact (deleted, customer_id);
CREATE INDEX idx_contact_deleted_name ON contact (deleted, name);
CREATE INDEX idx_contact_deleted_phone ON contact (deleted, phone);

CREATE TABLE audit_log (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id    BIGINT,
  actor_name  VARCHAR(50),
  action      VARCHAR(50)  NOT NULL,
  entity_type VARCHAR(50)  NOT NULL,
  entity_id   BIGINT,
  detail      VARCHAR(500),
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_audit_entity ON audit_log (entity_type, entity_id);
CREATE INDEX idx_audit_created ON audit_log (created_at);

CREATE TABLE `user` (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      VARCHAR(50)  NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  display_name  VARCHAR(50)  NOT NULL,
  role          VARCHAR(20)  NOT NULL,
  enabled       BOOLEAN      DEFAULT TRUE,
  last_login_at TIMESTAMP,
  token_version INT          DEFAULT 0,
  deleted       INT          DEFAULT 0,
  version       INT          DEFAULT 0,
  created_at    TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_user_username UNIQUE (username)
);

CREATE TABLE customer (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           VARCHAR(100) NOT NULL,
  company        VARCHAR(100) NOT NULL,
  contact_person VARCHAR(50),
  phone          VARCHAR(30),
  email          VARCHAR(100),
  address        VARCHAR(255),
  remark         VARCHAR(500),
  status         VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  deleted        INT          DEFAULT 0,
  version        INT          DEFAULT 0,
  created_by     BIGINT,
  created_at     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
  active_key     VARCHAR(255) AS (CASE WHEN deleted = 0 THEN CONCAT(name, '||', company) ELSE NULL END),
  CONSTRAINT uk_customer_active_name_company UNIQUE (active_key)
);
CREATE INDEX idx_customer_deleted_company ON customer (deleted, company);
CREATE INDEX idx_customer_deleted_name ON customer (deleted, name);
CREATE INDEX idx_customer_deleted_phone ON customer (deleted, phone);

CREATE TABLE opportunity (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id         BIGINT       NOT NULL,
  name                VARCHAR(100) NOT NULL,
  expected_amount_min BIGINT       DEFAULT 0,
  expected_amount_max BIGINT       DEFAULT 0,
  remark              VARCHAR(500),
  status              VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
  deleted             INT          DEFAULT 0,
  version             INT          DEFAULT 0,
  created_by          BIGINT,
  created_at          TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
  updated_at          TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_opportunity_deleted_customer ON opportunity (deleted, customer_id);
CREATE INDEX idx_opportunity_deleted_name ON opportunity (deleted, name);

CREATE TABLE sales_opportunity (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  opportunity_id      BIGINT      NOT NULL,
  amount              BIGINT      DEFAULT 0,
  stage               VARCHAR(30) NOT NULL,
  expected_close_date DATE,
  close_result        VARCHAR(20),
  closed_at           TIMESTAMP,
  deleted             INT         DEFAULT 0,
  version             INT         DEFAULT 0,
  created_by          BIGINT,
  created_at          TIMESTAMP   DEFAULT CURRENT_TIMESTAMP,
  updated_at          TIMESTAMP   DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_so_deleted_stage ON sales_opportunity (deleted, stage);
CREATE INDEX idx_so_deleted_opportunity ON sales_opportunity (deleted, opportunity_id);

CREATE TABLE follow_up (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id       BIGINT,
  opportunity_id    BIGINT,
  lead_id           BIGINT,
  method            VARCHAR(20)   NOT NULL,
  content           VARCHAR(2000) NOT NULL,
  next_follow_up_at TIMESTAMP,
  follow_up_by      BIGINT        NOT NULL,
  deleted           INT           DEFAULT 0,
  version           INT           DEFAULT 0,
  created_at        TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
  updated_at        TIMESTAMP     DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_followup_customer_created ON follow_up (customer_id, created_at);
CREATE INDEX idx_followup_opportunity ON follow_up (opportunity_id);
CREATE INDEX idx_followup_lead ON follow_up (lead_id);

CREATE TABLE lead (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                  VARCHAR(50)  NOT NULL,
  company               VARCHAR(100) NOT NULL,
  title                 VARCHAR(50),
  phone                 VARCHAR(30),
  email                 VARCHAR(100),
  source                VARCHAR(20)  NOT NULL DEFAULT 'OTHER',
  status                VARCHAR(20)  NOT NULL DEFAULT 'NEW',
  score                 INT          NOT NULL DEFAULT 0,
  owner_id              BIGINT,
  converted_customer_id BIGINT,
  converted_at          TIMESTAMP,
  remark                VARCHAR(500),
  deleted               INT          DEFAULT 0,
  version               INT          DEFAULT 0,
  created_by            BIGINT,
  created_at            TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
  updated_at            TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_lead_deleted_status ON lead (deleted, status);
CREATE INDEX idx_lead_deleted_owner ON lead (deleted, owner_id);
CREATE INDEX idx_lead_deleted_company ON lead (deleted, company);
CREATE INDEX idx_lead_deleted_name ON lead (deleted, name);
CREATE INDEX idx_lead_deleted_source ON lead (deleted, source);

CREATE TABLE sales_target (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  target_month  VARCHAR(7) NOT NULL,
  target_amount BIGINT     NOT NULL,
  deleted       INT        DEFAULT 0,
  version       INT        DEFAULT 0,
  created_by    BIGINT,
  created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  active_key    VARCHAR(64) AS (CASE WHEN deleted = 0 THEN CONCAT('m||', target_month) ELSE NULL END),
  CONSTRAINT uk_sales_target_active_month UNIQUE (active_key)
);
CREATE INDEX idx_sales_target_deleted_month ON sales_target (deleted, target_month);

CREATE TABLE product (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code           VARCHAR(50)  NOT NULL,
  name           VARCHAR(100) NOT NULL,
  spec           VARCHAR(255),
  unit           VARCHAR(20),
  standard_price BIGINT       NOT NULL DEFAULT 0,
  status         VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
  deleted        INT          DEFAULT 0,
  version        INT          DEFAULT 0,
  created_by     BIGINT,
  created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  active_key     VARCHAR(64) AS (CASE WHEN deleted = 0 THEN CONCAT('p||', code) ELSE NULL END),
  CONSTRAINT uk_product_active_code UNIQUE (active_key)
);
CREATE INDEX idx_product_deleted_status ON product (deleted, status);
CREATE INDEX idx_product_deleted_name ON product (deleted, name);

CREATE TABLE quote (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quote_no       VARCHAR(30) NOT NULL,
  customer_id    BIGINT      NOT NULL,
  opportunity_id BIGINT,
  valid_until    DATE,
  status         VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
  total_amount   BIGINT      NOT NULL DEFAULT 0,
  remark         VARCHAR(500),
  approver_id    BIGINT,
  approved_at    TIMESTAMP,
  reject_reason  VARCHAR(500),
  deleted        INT         DEFAULT 0,
  version        INT         DEFAULT 0,
  created_by     BIGINT,
  created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  active_key     VARCHAR(64) AS (CASE WHEN deleted = 0 THEN CONCAT('q||', quote_no) ELSE NULL END),
  CONSTRAINT uk_quote_active_no UNIQUE (active_key)
);
CREATE INDEX idx_quote_deleted_customer ON quote (deleted, customer_id);
CREATE INDEX idx_quote_deleted_status ON quote (deleted, status);

CREATE TABLE quote_item (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quote_id     BIGINT       NOT NULL,
  product_id   BIGINT,
  product_name VARCHAR(100) NOT NULL,
  unit_price   BIGINT       NOT NULL,
  quantity     INT          NOT NULL,
  discount     DECIMAL(5,4) NOT NULL DEFAULT 1.0000,
  line_total   BIGINT       NOT NULL,
  deleted      INT          DEFAULT 0,
  version      INT          DEFAULT 0,
  created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_quote_item_quote ON quote_item (quote_id);

CREATE TABLE contract (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contract_no       VARCHAR(30)  NOT NULL,
  title             VARCHAR(200) NOT NULL,
  customer_id       BIGINT       NOT NULL,
  quote_id          BIGINT,
  amount            BIGINT       NOT NULL DEFAULT 0,
  start_date        DATE,
  end_date          DATE,
  content           CLOB,
  status            VARCHAR(30)  NOT NULL DEFAULT 'DRAFT',
  approver_id       BIGINT,
  approved_at       TIMESTAMP,
  reject_reason     VARCHAR(500),
  effective_at      TIMESTAMP,
  terminated_reason VARCHAR(500),
  remark            VARCHAR(500),
  deleted           INT          DEFAULT 0,
  version           INT          DEFAULT 0,
  created_by        BIGINT,
  created_at        TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at        TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  active_key        VARCHAR(64) AS (CASE WHEN deleted = 0 THEN CONCAT('c||', contract_no) ELSE NULL END),
  CONSTRAINT uk_contract_active_no UNIQUE (active_key)
);
CREATE INDEX idx_contract_deleted_customer ON contract (deleted, customer_id);
CREATE INDEX idx_contract_deleted_status ON contract (deleted, status);

