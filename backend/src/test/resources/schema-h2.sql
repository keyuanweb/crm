-- H2 (MySQL 兼容模式) 测试 schema，与 V1__init.sql 保持字段一致
--
-- 本脚本必须**幂等**：同一个 JVM 内可能出现多套 ApplicationContext（例如 AuthCaptchaIT 带
-- @TestPropertySource，其上下文键与 AbstractIntegrationTest 不同），而测试库是共享的
-- 具名内存库（jdbc:h2:mem:crm;DB_CLOSE_DELAY=-1）。第二套上下文会**重跑本脚本**。
--
-- 下列 22 张表原先只有建表、没有 DROP，脚本因此不是幂等的：重跑时 DROP 块先清掉 62 张表，
-- 建表语句随即在仍然存在的表上失败（首个是 lead），此时共享库已被清掉一半，
-- 导致该 JVM 内**其后所有用例**级联失败——而报错指向的是 lead 建表，与真正的调用链相隔很远。
-- 该缺陷在接入 failsafe 前不可见：AuthCaptchaIT 是 *IT，surefire 从不执行它。
--
-- **版本标记约定**（SchemaParityIT 的机械关联）：凡**不建表**的迁移（只加列、加索引、改可空、
-- 写种子），其影响的列/索引行尾以 `-- V<n>` 标注由哪条迁移引入。建表的迁移不需要标记——
-- SchemaParityIT 直接核对该迁移建的每一张表在本文件里都有 `CREATE TABLE`，那比一行注释更强。
-- 约定存在的理由：本文件是 2 000 余行的翻译产物，没有标记时"某个迁移是否已镜像"只能靠人读；
-- 标记让"新增迁移必须动本文件"成为可机械判定的事实（T072）。
-- 标注位置的正确性由评审与第一道（表名）检查承担，标记本身只证明"本文件被改动过"。
