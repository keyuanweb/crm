-- 1. custom_object:read（本迁移新增读码）→ 自定义对象**定义面**（全量对象列表，含字段定义与启停状态）。
--    授予范围 = 持有「自定义对象」菜单的角色（V75 给 ANALYST；ADMIN 靠菜单兜底 + 切面直通）。
--    这是 084 的实质扩权之一（另一处见 V86 的多币种读写分码，同以 FR-N24 批准，批准人 龙星，2026-09-12）：
--    CustomObjectController 的五个定义端点此前是类级 hasRole('ADMIN')，ANALYST 看得见「自定义对象」菜单、
--    勾得上，点进去恒 403。接线后 ANALYST 获得自定义对象的定义读写能力（读=本码，写=它 V75 就持有的
--    custom_object:create/update/delete）。
--    注意：/{id}/records*（对象**记录**的增删改查）不在本迁移范围内，仍是业务面端点。
INSERT INTO `role_permission` (`role_id`, `permission_code`)
SELECT r.id, 'custom_object:read' FROM `role` r WHERE r.code IN ('ADMIN', 'ANALYST');

